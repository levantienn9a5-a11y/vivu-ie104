const assert = require('node:assert/strict');
const {filterTrips} = require('./public/trip-filters.js');
const trip = (id,operator,clock) => ({id,operator,departure:'2026-11-11T'+clock});
const trips=[trip(1,'ViVu Express','00:00'),trip(2,'An Bình Travel','05:59'),trip(3,'ViVu Express','06:00'),trip(4,'ViVu Express','08:59'),trip(5,'Miền Xanh','09:00'),trip(6,'Hành Trình Việt','12:00'),trip(7,'Sao Việt Travel','15:00'),trip(8,'Đông Đô','18:00'),trip(9,'ViVu Express','21:00'),trip(10,'ViVu Express','23:59')];
const ids=rows=>rows.map(x=>x.id);
assert.deepEqual(ids(filterTrips(trips)),trips.map(x=>x.id));
assert.deepEqual(ids(filterTrips(trips,' VIVU  EXPRESS ')),[1,3,4,9,10]);
assert.deepEqual(ids(filterTrips(trips,'an binh')),[2]);
assert.deepEqual(ids(filterTrips(trips,'dong do')),[8]);
assert.deepEqual(ids(filterTrips(trips,'KHÔNG CÓ')),[]);
assert.deepEqual(ids(filterTrips(trips,'','0-180')),[1]);
assert.deepEqual(ids(filterTrips(trips,'','180-360')),[2]);
assert.deepEqual(ids(filterTrips(trips,'','360-540')),[3,4]);
assert.deepEqual(ids(filterTrips(trips,'','540-720')),[5]);
assert.deepEqual(ids(filterTrips(trips,'','720-900')),[6]);
assert.deepEqual(ids(filterTrips(trips,'','900-1080')),[7]);
assert.deepEqual(ids(filterTrips(trips,'','1080-1260')),[8]);
assert.deepEqual(ids(filterTrips(trips,'','1260-1440')),[9,10]);
assert.deepEqual(ids(filterTrips(trips,'vivu','360-540')),[3,4]);
assert.deepEqual(ids(filterTrips(trips,'an binh','360-540')),[]);
assert.equal(trips.length,10);
console.log('16 filter checks passed: operator names, accents, all 8 time ranges, boundaries and combined filters.');
